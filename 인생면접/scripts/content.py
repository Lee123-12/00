def segments(text):
    """'{{...}}' 표시를 기준으로 [(문자열, 빈칸여부), ...] 로 나눈다."""
    out = []
    rest = text
    while rest:
        start = rest.find("{{")
        if start < 0:
            out.append((rest, False))
            break
        if start:
            out.append((rest[:start], False))
        end = rest.find("}}", start)
        out.append((rest[start + 2:end], True))
        rest = rest[end + 2:]
    return out
