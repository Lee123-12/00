def segments(text):
    """'{{빈칸}}' · '**굵게**' 표시를 기준으로 [(문자열, 종류), ...] 로 나눈다.

    종류: "" (보통), "blank" (빈칸), "bold" (굵게)
    """
    out = []
    for part in re.split(r"(\{\{.*?\}\}|\*\*.*?\*\*)", text):
        if not part:
            continue
        if part.startswith("{{"):
            out.append((part[2:-2], "blank"))
        elif part.startswith("**"):
            out.append((part[2:-2], "bold"))
        else:
            out.append((part, ""))
    return out
